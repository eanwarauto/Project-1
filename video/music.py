    motif = [(0, 62, .4), (.45, 63, .4), (.9, 66, .5), (1.5, 67, .4), (1.95, 66, .4), (2.4, 63, .4), (2.85, 62, 1.0)]
    for k, t0 in enumerate((2.0, 5.6, 9.0)):
        melody(tr, t0, [(o, m + (12 if k == 1 else 0), d) for o, m, d in motif], pluck, 0.7, -0.1)
    # الكير: صمت موسيقي تقريباً — فقط نبض خافت منخفض
    for k in range(7): place(tr, 13.6 + k * 1.4, taiko(0.35), 0.5, 0, 0.3)
    # 24–29 صمت تام
    # العطّار: دفء رئيسي (ري الكبير)
    ch = [(29.5, [62, 66, 69]), (32.5, [59, 62, 66]), (35.5, [55, 59, 62]), (38.5, [57, 61, 64])]
    pads(tr, [(29.5, 32.5, [50, 57, 62, 66]), (32.5, 35.5, [47, 54, 59, 62]), (35.5, 38.5, [43, 50, 55, 59]), (38.5, 41.2, [45, 52, 57, 61])], 1.0)
    arp(tr, 30.5, 41, ch, 0.25, piano, 0.45, 12, (0, 1, 2, 1, 2, 0))
    melody(tr, 31, [(0, 74, 1), (1, 76, .5), (1.5, 78, 1.5), (3.5, 76, 1), (4.5, 74, 1), (5.5, 71, 2), (8, 74, 1), (9, 73, 2)], bell, 0.5, 0.1)
    # الكشف: ذروة
