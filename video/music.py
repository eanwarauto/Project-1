    pads(tr, [(1, 9, [45, 52, 57])], 0.6)
    # الريح: توتر متصاعد
    place(tr, 9.5, tremolo([57, 60, 63], 8.6, 0.9), 0.7, 0, 0.4)
    place(tr, 13, tremolo([45, 46], 5.1, 1.0, 14), 0.6, 0, 0.4)
