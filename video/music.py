    while t < 15.5:
        place(tr, t, piano(40 if k % 4 != 3 else 43, 0.3, 0.9), 0.55, 0, 0.3)
        t += 0.29; k += 1
    pads(tr, [(7.2, 11.4, [52, 55, 59]), (11.4, 15.6, [48, 52, 55])], 0.8)
