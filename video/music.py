"""موسيقى تصويرية أصلية مولّدة بالكود لأفلام «الصحبة الصالحة».
الفكرة: موسيقى + صمت مقصود في اللحظات الحاسمة، والقصة تصل بالصورة.
"""
import numpy as np
from audio import SR, T, lp, hp, bp, noise, boom, rng

A4 = 440.0


def hz(m):
    return A4 * 2 ** ((m - 69) / 12)


def _env(n, a, r):
    e = np.ones(n)
    na, nr = min(n, max(1, int(a * SR))), min(n, max(1, int(r * SR)))
    e[:na] = np.linspace(0, 1, na)
    e[-nr:] *= np.linspace(1, 0, nr) ** 2
    return e


# ---------- الآلات ----------
def piano(m, d=1.5, vel=1.0):
    f = hz(m); L = d + 1.8; t = T(L)
    y = np.zeros(len(t))
    for n in range(1, 9):
        fn = f * n * np.sqrt(1 + 0.0004 * n * n)
        if fn > 16000: break
        y += np.sin(2 * np.pi * fn * t + rng.uniform(0, 6)) * (1 / n ** 1.4) * np.exp(-t * (0.9 + n * 0.55) * (1 + (m - 60) / 40))
    damp = np.ones(len(t)); k = int(d * SR); damp[k:] = np.exp(-(t[k:] - d) * 5)
    y *= damp * _env(len(t), 0.004, 0.05)
    return y * vel * 0.5


def pluck(m, d=0.8, vel=1.0):
    """عود/قانون تقريبي"""
    f = hz(m); L = d + 1.0; t = T(L)
    bend = 1 + 0.004 * np.exp(-t * 30)
    ph = 2 * np.pi * f * np.cumsum(bend) / SR
    y = np.zeros(len(t))
    for n in range(1, 11):
        y += np.sin(n * ph) * (1 / n) * np.exp(-t * (2.2 + n * 0.9))
    y += bp(noise(L), 1500, 6000) * np.exp(-t * 80) * 0.15
    return y * _env(len(t), 0.002, 0.08) * vel * 0.45


def bell(m, d=2.5, vel=1.0):
    f = hz(m); t = T(d)
    y = np.sin(2 * np.pi * f * t) * np.exp(-t * 1.6) + 0.35 * np.sin(2 * np.pi * f * 4.01 * t) * np.exp(-t * 4) + 0.15 * np.sin(2 * np.pi * f * 2.76 * t) * np.exp(-t * 3)
    return y * _env(len(t), 0.002, 0.3) * vel * 0.35


def strings(ms, d, vel=1.0, att=1.4, rel=1.8, bright=2600):
    """وتريات: أصوات متعددة متفاوتة الضبط مع اهتزاز"""
    L = d + rel; t = T(L)
    y = np.zeros(len(t))
    for m in ms:
        f = hz(m)
        for v, det in enumerate((-0.0025, 0.0, 0.0028)):
            vib = 1 + 0.003 * np.sin(2 * np.pi * (5 + v * 0.4) * t + v * 2) + det
            ph = 2 * np.pi * f * np.cumsum(vib) / SR
            for n in range(1, 12):
                if f * n > bright * 2.2: break
                y += np.sin(n * ph + v) * (1 / n) * (0.6 if n > 1 else 1)
    y = lp(y, bright, 2)
    e = np.ones(len(t)); na = int(att * SR); e[:na] = np.linspace(0, 1, na) ** 1.6
    k = int(d * SR); e[k:] *= np.linspace(1, 0, len(t) - k) ** 2
    return y * e * vel * 0.06 / max(1, len(ms)) ** 0.5


def drone(ms, d, vel=1.0):
    m = ms[0] if isinstance(ms, (list, tuple)) else ms
    return strings([m - 12, m - 5, m], d, vel * 1.6, att=3, rel=3, bright=900)


def taiko(vel=1.0):
    return boom(1.6, 62, 1.0) * vel * 0.9


def tremolo(ms, d, vel=1.0, rate=11):
    y = strings(ms, d, vel, att=0.6, rel=0.8, bright=3200)
    t = T(len(y) / SR)
    return y * (0.55 + 0.45 * np.abs(np.sin(np.pi * rate * t)))


# ---------- أدوات التأليف ----------
def place(tr, t, x, gain=1.0, pan=0.0, wet=0.45):
    tr.add(t, x, gain, pan, wet)


def arp(tr, t0, t1, chords, step, inst=piano, gain=0.6, octave=0, pattern=(0, 1, 2, 1), pan=0.15):
    """أربيجيو على تتابع كوردات: chords = [(t, [midi...]), ...]"""
    t = t0; k = 0
    while t < t1:
        ch = [c for tc, c in chords if tc <= t][-1]
        m = ch[pattern[k % len(pattern)] % len(ch)] + octave
        place(tr, t, inst(m, step * 1.6, 0.8 + 0.2 * rng.random()), gain, pan * (1 if k % 2 else -1))
        t += step; k += 1


def melody(tr, t0, notes, inst=piano, gain=0.8, pan=0.0, wet=0.5):
    """notes = [(offset, midi, dur), ...]"""
    for off, m, d in notes:
        place(tr, t0 + off, inst(m, d), gain, pan, wet)


def pads(tr, chords, gain=1.0, inst=strings):
    """chords = [(t0, t1, [midi...]), ...]"""
    for t0, t1, ms in chords:
        place(tr, t0, inst(ms, t1 - t0), gain, 0, 0.5)


