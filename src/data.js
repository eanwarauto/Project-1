function shells(z) {
  if (z === 21) return [2, 8, 9, 2];
  const caps = [2, 8, 8, 2];
  const out = [];
  let left = z;
  for (const c of caps) {
    if (left <= 0) break;
    out.push(Math.min(c, left));
    left -= c;
  }
  return out;
}

